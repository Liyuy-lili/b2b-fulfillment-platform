-- Project-authored V1. M1 activates order, item and command only.
-- DATETIME audit values in ful_* tables are UTC.

CREATE TABLE ful_order (
  id BIGINT NOT NULL AUTO_INCREMENT,
  erp_order_id BIGINT NOT NULL,
  order_no VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
  customer_id BIGINT NOT NULL,
  owner_user_id BIGINT NOT NULL,
  account_id BIGINT NULL,
  sale_user_id BIGINT NULL,
  status VARCHAR(32) NOT NULL,
  allocation_attempted BIT(1) NOT NULL DEFAULT b'0',
  allocation_strategy VARCHAR(32) NOT NULL DEFAULT 'PRIORITY',
  strategy_version INT NOT NULL DEFAULT 1,
  version BIGINT NOT NULL DEFAULT 0,
  total_price DECIMAL(24,6) NOT NULL,
  discount_percent DECIMAL(24,6) NOT NULL,
  discount_price DECIMAL(24,6) NOT NULL,
  deposit_price DECIMAL(24,6) NOT NULL,
  tenant_id BIGINT NOT NULL,
  creator VARCHAR(64) NOT NULL DEFAULT '',
  create_time DATETIME(6) NOT NULL,
  updater VARCHAR(64) NOT NULL DEFAULT '',
  update_time DATETIME(6) NOT NULL,
  deleted BIT(1) NOT NULL DEFAULT b'0',
  PRIMARY KEY (id),
  UNIQUE KEY uk_tenant_id (tenant_id,id),
  UNIQUE KEY uk_order_source (tenant_id,erp_order_id),
  UNIQUE KEY uk_order_no (tenant_id,order_no),
  KEY ix_order_status (tenant_id,status,create_time,id),
  KEY ix_order_owner (tenant_id,owner_user_id,id),
  CONSTRAINT ck_order_status CHECK (status IN ('NEW','WAIT_STOCK','RESERVED','PARTIALLY_SHIPPED','FULFILLED','CANCELLED','PARTIALLY_CLOSED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE ful_order_item (
  id BIGINT NOT NULL AUTO_INCREMENT,
  order_id BIGINT NOT NULL,
  erp_order_item_id BIGINT NOT NULL,
  product_id BIGINT NOT NULL,
  unit_id BIGINT NOT NULL,
  price_snapshot DECIMAL(24,6) NOT NULL,
  tax_percent DECIMAL(24,6) NOT NULL,
  tax_price DECIMAL(24,6) NOT NULL,
  total_price DECIMAL(24,6) NOT NULL,
  ordered_qty DECIMAL(24,6) NOT NULL,
  open_qty DECIMAL(24,6) NOT NULL,
  reserved_qty DECIMAL(24,6) NOT NULL DEFAULT 0,
  shipped_qty DECIMAL(24,6) NOT NULL DEFAULT 0,
  cancelled_qty DECIMAL(24,6) NOT NULL DEFAULT 0,
  returned_qty DECIMAL(24,6) NOT NULL DEFAULT 0,
  tenant_id BIGINT NOT NULL,
  creator VARCHAR(64) NOT NULL DEFAULT '',
  create_time DATETIME(6) NOT NULL,
  updater VARCHAR(64) NOT NULL DEFAULT '',
  update_time DATETIME(6) NOT NULL,
  deleted BIT(1) NOT NULL DEFAULT b'0',
  PRIMARY KEY (id),
  UNIQUE KEY uk_tenant_id (tenant_id,id),
  UNIQUE KEY uk_item_source (tenant_id,erp_order_item_id),
  KEY ix_item_order (tenant_id,order_id,id),
  CONSTRAINT fk_item_order FOREIGN KEY (tenant_id,order_id) REFERENCES ful_order(tenant_id,id),
  CONSTRAINT ck_item_quantities CHECK (ordered_qty>0 AND open_qty>=0 AND reserved_qty>=0 AND shipped_qty>=0 AND cancelled_qty>=0 AND returned_qty>=0 AND returned_qty<=shipped_qty AND ordered_qty=open_qty+reserved_qty+shipped_qty+cancelled_qty)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE ful_reservation (
  id BIGINT NOT NULL AUTO_INCREMENT,
  reservation_no VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
  order_id BIGINT NOT NULL,
  order_item_id BIGINT NOT NULL,
  product_id BIGINT NOT NULL,
  warehouse_id BIGINT NOT NULL,
  allocation_round INT NOT NULL,
  allocated_qty DECIMAL(24,6) NOT NULL,
  held_qty DECIMAL(24,6) NOT NULL,
  consumed_qty DECIMAL(24,6) NOT NULL DEFAULT 0,
  released_qty DECIMAL(24,6) NOT NULL DEFAULT 0,
  active_flag BIT(1) NOT NULL,
  expire_at DATETIME(6) NOT NULL,
  version BIGINT NOT NULL DEFAULT 0,
  tenant_id BIGINT NOT NULL,
  creator VARCHAR(64) NOT NULL DEFAULT '',
  create_time DATETIME(6) NOT NULL,
  updater VARCHAR(64) NOT NULL DEFAULT '',
  update_time DATETIME(6) NOT NULL,
  deleted BIT(1) NOT NULL DEFAULT b'0',
  PRIMARY KEY (id),
  UNIQUE KEY uk_tenant_id (tenant_id,id),
  UNIQUE KEY uk_reservation_no (tenant_id,reservation_no),
  KEY ix_reservation_order (tenant_id,order_id,id),
  KEY ix_reservation_expiry (active_flag,expire_at,id),
  CONSTRAINT fk_reservation_order FOREIGN KEY (tenant_id,order_id) REFERENCES ful_order(tenant_id,id),
  CONSTRAINT fk_reservation_item FOREIGN KEY (tenant_id,order_item_id) REFERENCES ful_order_item(tenant_id,id),
  CONSTRAINT ck_reservation_qty CHECK (allocated_qty>0 AND held_qty>=0 AND consumed_qty>=0 AND released_qty>=0 AND allocated_qty=held_qty+consumed_qty+released_qty)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE ful_shipment (
  id BIGINT NOT NULL AUTO_INCREMENT,
  shipment_no VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
  order_id BIGINT NOT NULL,
  warehouse_id BIGINT NOT NULL,
  erp_sale_out_id BIGINT NULL,
  status VARCHAR(32) NOT NULL,
  carrier_code VARCHAR(64) NULL,
  tracking_no VARCHAR(128) NULL,
  shipped_at DATETIME(6) NULL,
  delivered_at DATETIME(6) NULL,
  tenant_id BIGINT NOT NULL,
  creator VARCHAR(64) NOT NULL DEFAULT '',
  create_time DATETIME(6) NOT NULL,
  updater VARCHAR(64) NOT NULL DEFAULT '',
  update_time DATETIME(6) NOT NULL,
  deleted BIT(1) NOT NULL DEFAULT b'0',
  PRIMARY KEY (id),
  UNIQUE KEY uk_tenant_id (tenant_id,id),
  UNIQUE KEY uk_shipment_no (tenant_id,shipment_no),
  UNIQUE KEY uk_shipment_erp (tenant_id,erp_sale_out_id),
  KEY ix_shipment_warehouse (tenant_id,warehouse_id,create_time,id),
  CONSTRAINT fk_shipment_order FOREIGN KEY (tenant_id,order_id) REFERENCES ful_order(tenant_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE ful_shipment_item (
  id BIGINT NOT NULL AUTO_INCREMENT,
  shipment_id BIGINT NOT NULL,
  order_item_id BIGINT NOT NULL,
  reservation_id BIGINT NOT NULL,
  quantity DECIMAL(24,6) NOT NULL,
  erp_sale_out_item_id BIGINT NULL,
  tenant_id BIGINT NOT NULL,
  creator VARCHAR(64) NOT NULL DEFAULT '',
  create_time DATETIME(6) NOT NULL,
  updater VARCHAR(64) NOT NULL DEFAULT '',
  update_time DATETIME(6) NOT NULL,
  deleted BIT(1) NOT NULL DEFAULT b'0',
  PRIMARY KEY (id),
  UNIQUE KEY uk_tenant_id (tenant_id,id),
  UNIQUE KEY uk_shipment_reservation (tenant_id,shipment_id,reservation_id),
  KEY ix_shipment_order_item (tenant_id,order_item_id),
  CONSTRAINT fk_shipment_item_head FOREIGN KEY (tenant_id,shipment_id) REFERENCES ful_shipment(tenant_id,id),
  CONSTRAINT fk_shipment_item_order FOREIGN KEY (tenant_id,order_item_id) REFERENCES ful_order_item(tenant_id,id),
  CONSTRAINT fk_shipment_item_res FOREIGN KEY (tenant_id,reservation_id) REFERENCES ful_reservation(tenant_id,id),
  CONSTRAINT ck_shipment_qty CHECK (quantity>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE ful_command_record (
  id BIGINT NOT NULL AUTO_INCREMENT,
  actor_id BIGINT NOT NULL,
  command_type VARCHAR(32) COLLATE utf8mb4_bin NOT NULL,
  idempotency_key VARCHAR(128) COLLATE utf8mb4_bin NOT NULL,
  request_hash CHAR(64) COLLATE utf8mb4_bin NOT NULL,
  response_code INT NULL,
  response_json JSON NULL,
  tenant_id BIGINT NOT NULL,
  creator VARCHAR(64) NOT NULL DEFAULT '',
  create_time DATETIME(6) NOT NULL,
  updater VARCHAR(64) NOT NULL DEFAULT '',
